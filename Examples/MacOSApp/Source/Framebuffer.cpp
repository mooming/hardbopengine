Framebuffer::Framebuffer()
	: data(nullptr)
	, width(0)
	, height(0)
	, pitch(0)
{
}

Framebuffer::~Framebuffer()
{
	if (data != nullptr)
	{
		std::free(data);
		data = nullptr;
	}
}

bool Framebuffer::Initialize(int inWidth, int inHeight)
{
	if (inWidth <= 0 || inHeight <= 0)
	{
		std::cerr << "Error: Framebuffer::Initialize - invalid dimensions ("
		          << inWidth << "x" << inHeight << ")" << std::endl;
		return false;
	}

	const size_t newPitch = static_cast<size_t>(inWidth) * 4;
	const size_t newSize = newPitch * static_cast<size_t>(inHeight);

	uint32_t* newData = static_cast<uint32_t*>(std::malloc(newSize));
	if (newData == nullptr)
	{
		std::cerr << "Error: Framebuffer::Initialize - allocation failed ("
		          << newSize << " bytes)" << std::endl;
		return false;
	}

	if (data != nullptr)
	{
		std::free(data);
	}

	data = newData;
	width = inWidth;
	height = inHeight;
	pitch = newPitch;

	return true;
}

void Framebuffer::Clear(uint32_t color) noexcept
{
	if (data == nullptr)
	{
		return;
	}

	const size_t numPixels = pitch * static_cast<size_t>(height) / 4;
	for (size_t i = 0; i < numPixels; ++i)
	{
		data[i] = color;
	}
}

void Framebuffer::SetPixel(int x, int y, uint32_t color) noexcept
{
	if (data == nullptr)
	{
		return;
	}

	if (x < 0 || y < 0 || x >= width || y >= height)
	{
		return;
	}

	const size_t index = static_cast<size_t>(y) * (pitch / 4) + static_cast<size_t>(x);
	data[index] = color;
}

uint32_t Framebuffer::GetPixel(int x, int y) const noexcept
{
	if (data == nullptr)
	{
		return 0;
	}

	if (x < 0 || y < 0 || x >= width || y >= height)
	{
		return 0;
	}

	const size_t index = static_cast<size_t>(y) * (pitch / 4) + static_cast<size_t>(x);
	return data[index];
}

void Framebuffer::FillRect(int x, int y, int w, int h, uint32_t color) noexcept
{
	if (data == nullptr)
	{
		return;
	}

	// Clip to framebuffer bounds
	if (x < 0)
	{
		w += x;
		x = 0;
	}
	if (y < 0)
	{
		h += y;
		y = 0;
	}
	if (x + w > width)
	{
		w = width - x;
	}
	if (y + h > height)
	{
		h = height - y;
	}

	if (w <= 0 || h <= 0)
	{
		return;
	}

	const size_t rowStride = pitch / 4;
	for (int row = y; row < y + h; ++row)
	{
		uint32_t* rowPtr = data + static_cast<size_t>(row) * rowStride + static_cast<size_t>(x);
		for (int col = 0; col < w; ++col)
		{
			rowPtr[col] = color;
		}
	}
}

void Framebuffer::DrawLine(int x0, int y0, int x1, int y1, uint32_t color) noexcept
{
	// Bresenham's line algorithm
	const int dx = std::abs(x1 - x0);
	const int dy = std::abs(y1 - y0);
	const int sx = (x0 < x1) ? 1 : -1;
	const int sy = (y0 < y1) ? 1 : -1;
	int err = dx - dy;

	int cx = x0;
	int cy = y0;

	while (true)
	{
		SetPixel(cx, cy, color);

		if (cx == x1 && cy == y1)
		{
			break;
		}

		const int err2 = 2 * err;
		if (err2 > -dy)
		{
			err -= dy;
			cx += sx;
		}
		if (err2 < dx)
		{
			err += dx;
			cy += sy;
		}
	}
}

void Framebuffer::DrawChar(int x, int y, char ch, uint32_t color) noexcept
{
	if (data == nullptr)
	{
		return;
	}

	const int charIndex = static_cast<int>(ch) - 32;
	if (charIndex < 0 || charIndex >= 96)
	{
		return;
	}

	const uint8_t* glyph = Font8x12[charIndex];

	for (int row = 0; row < FontHeight; ++row)
	{
		const uint8_t bits = glyph[row];
		for (int col = 0; col < FontWidth; ++col)
		{
			if (bits & (0x80 >> col))
			{
				SetPixel(x + col, y + row, color);
			}
		}
	}
}

void Framebuffer::DrawText(int x, int y, const char* text, uint32_t color) noexcept
{
	if (text == nullptr || data == nullptr)
	{
		return;
	}

	int cursorX = x;

	while (*text != '\0')
	{
		DrawChar(cursorX, y, *text, color);
		cursorX += FontWidth + CharSpacing;
		++text;
	}
}

void Framebuffer::BitBlt(const Framebuffer* src, int dstX, int dstY) noexcept
{
	if (src == nullptr || src->data == nullptr || data == nullptr)
	{
		return;
	}

	const int srcW = src->width;
	const int srcH = src->height;
	const size_t srcStride = src->pitch / 4;
	const size_t dstStride = pitch / 4;

	// Calculate clipping
	int srcStartX = 0;
	int srcStartY = 0;
	int copyW = srcW;
	int copyH = srcH;

	if (dstX < 0)
	{
		srcStartX = -dstX;
		copyW -= srcStartX;
		dstX = 0;
	}
	if (dstY < 0)
	{
		srcStartY = -dstY;
		copyH -= srcStartY;
		dstY = 0;
	}
	if (dstX + copyW > width)
	{
		copyW = width - dstX;
	}
	if (dstY + copyH > height)
	{
		copyH = height - dstY;
	}

	if (copyW <= 0 || copyH <= 0)
	{
		return;
	}

	for (int row = 0; row < copyH; ++row)
	{
		const uint32_t* srcRow = src->data + static_cast<size_t>(srcStartY + row) * srcStride + static_cast<size_t>(srcStartX);
		uint32_t* dstRow = data + static_cast<size_t>(dstY + row) * dstStride + static_cast<size_t>(dstX);
		std::memcpy(dstRow, srcRow, static_cast<size_t>(copyW) * 4);
	}
}

uint32_t* Framebuffer::GetData() noexcept
{
	return data;
}

const uint32_t* Framebuffer::GetData() const noexcept
{
	return data;
}

int Framebuffer::GetWidth() const noexcept
{
	return width;
}

int Framebuffer::GetHeight() const noexcept
{
	return height;
}

size_t Framebuffer::GetPitch() const noexcept
{
	return pitch;
}

